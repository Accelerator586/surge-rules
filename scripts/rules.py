#!/usr/bin/env python3
"""Build and audit domain-only Surge rules with Python's standard library."""
import argparse
from collections import Counter
import hashlib
import ipaddress
import json
from pathlib import Path
import re
import sys
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
TYPES = {"DOMAIN", "DOMAIN-SUFFIX"}
# Service groups precede the general proxy override, and all precede CN.
ORDER = ["cn-allow", "reject", "ai", "apple", "parsec", "encrypted-sni", "proxy", "cn"]


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def dump_json(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def domain(value):
    value = value.strip().rstrip(".").lower().encode("idna").decode("ascii")
    if len(value) > 253 or "." not in value:
        raise ValueError(f"Not a service domain: {value!r}")
    try:
        ipaddress.ip_address(value)
    except ValueError:
        pass
    else:
        raise ValueError(f"IP address is not a domain rule: {value}")
    if not all(re.fullmatch(r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?", p)
               for p in value.split(".")):
        raise ValueError(f"Invalid domain: {value!r}")
    return value


def exclusions(policy, group):
    # Single-label and public suffix exceptions are skipped before domain().
    if group == "cn-allow":
        group = "cn"
    return {v.encode("idna").decode("ascii").lower()
            for v in policy.get("exclude", {}).get(group, [])}


def parse(text, *, group, policy, upstream=False):
    result, skipped = set(), Counter()
    excluded = exclusions(policy, group)
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(",")]
        kind = parts[0]
        if kind not in TYPES:
            if upstream:
                skipped[kind] += 1
                continue
            raise ValueError(f"{group}:{number}: Forbidden rule type: {kind}")
        if len(parts) != 2:
            raise ValueError(f"{group}:{number}: Expected TYPE,domain; no policy or flags")
        name = parts[1].rstrip(".").lower().encode("idna").decode("ascii")
        if name == policy["ignored_source_domain"] or name in excluded:
            if not upstream:
                raise ValueError(f"{group}:{number}: Excluded domain: {name}")
            skipped["EXCLUDED"] += 1
            continue
        name = domain(name)
        result.add((kind, name))
    return result, dict(sorted(skipped.items()))


def collect(root=ROOT):
    policy = read_json(root / "policy.json")
    lock = read_json(root / "sources.lock.json")
    if set(policy["groups"]) != set(ORDER):
        raise ValueError("Unexpected group registry")
    groups, audit = {}, {}
    for group in ORDER:
        rules, _ = parse((root / "rules" / f"{group}.list").read_text(),
                         group=group, policy=policy)
        groups[group] = rules
    for source in lock["sources"]:
        path = root / source["snapshot"]
        if not path.resolve().is_relative_to((root / "vendor").resolve()):
            raise ValueError("Source snapshot must live inside vendor/")
        data = path.read_bytes()
        if digest(data) != source["sha256"]:
            raise ValueError(f"Source integrity mismatch: {source['snapshot']}")
        rules, skipped = parse(data.decode("utf-8"), group=source["id"],
                               policy=policy, upstream=True)
        if len(rules) < source["minimum_domains"]:
            raise ValueError(f"Source unexpectedly empty/small: {source['id']}")
        groups[source["id"]].update(rules)
        audit[source["id"]] = {"sha256": source["sha256"],
                                "accepted": len(rules), "skipped": skipped}
    if not groups["cn"] or not groups["ai"]:
        raise ValueError("Missing positive controls: CN and AI must be nonempty")
    return policy, groups, audit


def matches(host, rule):
    kind, name = rule
    return host == name or (kind == "DOMAIN-SUFFIX" and host.endswith("." + name))


def explain(host, groups):
    host = host.rstrip(".").lower()
    for group in ORDER:
        for rule in sorted(groups[group]):
            if matches(host, rule):
                return group, ",".join(rule)
    return "final", "FINAL,Proxy,dns-failed"


def render(root=ROOT):
    policy, groups, audit = collect(root)
    result = {}
    for group in ORDER:
        lines = ["# Generated by scripts/rules.py; edit rules/ instead.",
                 "# SPDX-License-Identifier: AGPL-3.0-only",
                 "# Domain-only classification; unmatched requests use FINAL proxy."]
        lines += [",".join(rule) for rule in sorted(groups[group], key=lambda r: (r[1], r[0]))]
        result[f"{group}.list"] = "\n".join(lines) + "\n"
    result["manifest.json"] = dump_json({"schema": 1, "counts": {g: len(groups[g]) for g in ORDER},
                                          "source_audit": audit})
    base = f"https://raw.githubusercontent.com/{policy['repository']}/main/dist"
    lines = ["# Insert into your existing [Rule] section; keep private LAN/home rules locally.",
             "# Put cn-allow.list BEFORE any external advertising rules.",
             "# Put the remaining subscriptions AFTER external advertising rules.",
             "# Keep the existing Figma-specific rules before these general service rules."]
    for group in ORDER:
        lines.append(f"RULE-SET,{base}/{group}.list,{policy['policies'][group]},no-resolve,update-interval=3600")
    lines.append("FINAL,Proxy,dns-failed")
    result["surge-rules.conf"] = "\n".join(lines) + "\n"
    # Credential-free profile for Surge syntax validation, not a production proxy.
    profile = ["[General]", "[Proxy Group]"]
    for name in sorted(set(policy["policies"].values()) - {"REJECT"}):
        profile.append(f"{name} = select, DIRECT")
    profile.extend(["[Rule]"])
    for group in ORDER:
        profile.append(f"RULE-SET,{group}.list,{policy['policies'][group]},no-resolve")
    profile.append("FINAL,Proxy,dns-failed")
    result["validation.conf"] = "\n".join(profile) + "\n"
    return result


def build(root=ROOT, check=False):
    expected = render(root)
    output = root / "dist"
    if check:
        if not output.is_dir():
            raise ValueError("Missing dist/; run build")
        actual = {p.name for p in output.iterdir() if p.is_file()}
        if actual != set(expected):
            raise ValueError("dist/ file inventory differs; run build")
        for name, text in expected.items():
            if (output / name).read_text() != text:
                raise ValueError(f"Stale generated file: dist/{name}")
    else:
        output.mkdir(exist_ok=True)
        for name, text in expected.items():
            (output / name).write_text(text, encoding="utf-8")
    return read_json(output / "manifest.json")["counts"]


def download(url):
    if not url.startswith("https://ruleset.skk.moe/List/non_ip/"):
        raise ValueError(f"Unapproved source URL: {url}")
    request = urllib.request.Request(url, headers={"User-Agent": "surge-rules-maintainer/1"})
    with urllib.request.urlopen(request, timeout=40) as response:
        if not response.geturl().startswith("https://ruleset.skk.moe/"):
            raise ValueError("Unexpected upstream redirect")
        data = response.read(2_000_001)
    if not data or len(data) > 2_000_000:
        raise ValueError("Empty or oversized upstream response")
    return data


def update(root=ROOT):
    # Stage every response and validate the whole proposed tree before changing files.
    import tempfile
    import shutil
    _, before, _ = collect(root)
    lock = read_json(root / "sources.lock.json")
    with tempfile.TemporaryDirectory() as tmp:
        staged = Path(tmp) / "rules"
        shutil.copytree(root, staged, ignore=shutil.ignore_patterns(".git", "__pycache__"))
        for source in lock["sources"]:
            data = download(source["url"])
            (staged / source["snapshot"]).write_bytes(data)
            source["sha256"] = digest(data)
        (staged / "sources.lock.json").write_text(dump_json(lock))
        _, after, _ = collect(staged)
        build(staged)
        changes = []
        for group in ORDER:
            added, removed = sorted(after[group] - before[group]), sorted(before[group] - after[group])
            if added or removed:
                changes.append(f"## {group}: +{len(added)} / -{len(removed)}\n")
                for label, entries in [("Added", added), ("Removed", removed)]:
                    if entries:
                        changes.append(f"{label}:\n\n```\n" + "\n".join(",".join(x) for x in entries) + "\n```\n")
        if not changes:
            print("No effective domain-rule changes; source snapshots remain pinned.")
            return False
        report = ("# Upstream update proposal\n\n"
                  "CN additions expand direct access and require review. No automatic merge.\n\n"
                  + "\n".join(changes))
        for source in lock["sources"]:
            shutil.copyfile(staged / source["snapshot"], root / source["snapshot"])
        (root / "sources.lock.json").write_text(dump_json(lock))
        build(root)
        (root / "docs").mkdir(exist_ok=True)
        (root / "docs" / "UPSTREAM-UPDATE.md").write_text(report)
        print(report)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["build", "check", "update", "explain"])
    parser.add_argument("host", nargs="?")
    args = parser.parse_args()
    try:
        if args.command in {"build", "check"}:
            print(dump_json(build(check=args.command == "check")), end="")
        elif args.command == "update":
            update()
        else:
            if not args.host:
                parser.error("explain requires a hostname")
            _, groups, _ = collect()
            group, rule = explain(args.host, groups)
            print(f"{args.host} -> {group}: {rule}")
    except (ValueError, OSError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
